public class Exemplo1 {
    public static void main(String[] args) {

    // ================ Vetores ================== //

    int n[] = new int[4]; // Quatro locais

    /* -----------------------------------------------------------------------
        O "n[]" será o nome da nossa veriável.
        É o número nó "int[?]" será a quantidade de locais para guardar dados.
        Os "locais" são todos objetos.
    ----------------------------------------------------------------------- */

    // ------- Atribuindo valores a Vetores. ------- //

        n[0] = 1; // Na posição [0], terá o valor de 1.
        n[1] = 7; // Na posição [1], terá o valor de 7.
        n[2] = 4; // Na posição [2], terá o valor de 4.
        n[3] = 9; // Na posição [3], terá o valor de 9.

    // --- Uma segunda forma de atribuir valores é. --- //

        int r[] = {10, 5, 8, 7, 33}; /* Essa forma atribui valores diretamente
                                        tbm já definindo quantos objetos terá. */

        

    /* ---------------------------------------------------------------------
        Observação : No JAVA o primeiro Vetor, sempre! começa com 0
        ou seja sem será (0,....).
       --------------------------------------------------------------------- */ 

    }
}